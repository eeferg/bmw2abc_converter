"""Build bmw2abc_converter/grace_prefs.py from a corpus of BWW files.

Usage: uv run python scripts/build_grace_prefs.py LEE_DIR > bmw2abc_converter/grace_prefs.py

For each embellishment token followed by a melody note, counts
(ABC grace string, ABC pitch of the note) -> BWW token, and writes the most
frequent token per key. The output holds only token statistics, no tune content.
"""

from __future__ import annotations

import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from bmw2abc_converter.grace_notes import GRACE  # noqa: E402

NOTE_RE = re.compile(r"(LG|LA|B|C|D|E|F|HG|HA)[rl]?_\d+$")
BWW_TO_PITCH = {"LG": "G", "LA": "A", "B": "B", "C": "c", "D": "d",
                "E": "e", "F": "f", "HG": "g", "HA": "a"}
SKIP_RE = re.compile(r"^(\^ts|\^[2-7]s|(sharp|flat|natural)\w+)$")


def main(corpus: str) -> None:
    counts: dict[tuple[str, str], Counter] = defaultdict(Counter)
    files = [p for p in Path(corpus).rglob("*") if p.suffix.lower() in (".bww", ".bmw")]
    for path in files:
        tokens = path.read_text(encoding="latin-1").split()
        for i, tok in enumerate(tokens):
            if tok not in GRACE:
                continue
            j = i + 1
            while j < len(tokens) and SKIP_RE.match(tokens[j]):
                j += 1
            if j < len(tokens) and (m := NOTE_RE.match(tokens[j])):
                counts[(GRACE[tok], BWW_TO_PITCH[m.group(1)])][tok] += 1
    print('"""Embellishment preferences: (ABC grace, following ABC pitch) -> BWW token.')
    print()
    print("Generated by scripts/build_grace_prefs.py from token frequencies in")
    print(f"{len(files)} BWW files; contains no tune content. Do not edit by hand.")
    print('"""')
    print()
    print("GRACE_PREFS: dict[tuple[str, str], str] = {")
    for key in sorted(counts):
        tok, _ = counts[key].most_common(1)[0]
        print(f"    {key!r}: {tok!r},")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
